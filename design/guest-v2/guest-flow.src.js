function filterList(list,f){
  return list.filter(p=>(!f.specs.size||p.specs.some(s=>f.specs.has(s)))&&(!f.conds.size||p.conds.some(c=>f.conds.has(c)))
    &&(!f.langs.size||p.langs.some(l=>f.langs.has(l)))&&(f.gender==="any"||p.gender===f.gender)&&(!f.hosp.size||p.hosp.some(h=>f.hosp.has(h)))
    &&(f.dist==="any"||!S.loc||distTo(p)<=+f.dist)&&(!f.accepting||p.accepting)&&(!f.online||p.online));
}
function results(f=S.filters){
  const pq=S.pq||parse("");
  let list=filterList(PROV.filter(p=>matches(p,pq)),f);
  const az=(a,b)=>a.last.localeCompare(b.last)||a.first.localeCompare(b.first);
  const byRel=(a,b)=>relevance(b,pq)-relevance(a,pq)||(S.loc?distTo(a)-distTo(b):0)||az(a,b);
  if(S.sort==="distance"&&S.loc)list.sort((a,b)=>distTo(a)-distTo(b)||az(a,b));
  else if(S.sort==="az")list.sort(az);
  else if(S.sort==="featured")list.sort((a,b)=>(b.featured-a.featured)||byRel(a,b));
  else list.sort(byRel);
  return list;
}
function filterCount(f=S.filters){return f.specs.size+f.conds.size+f.langs.size+f.hosp.size+(f.gender!=="any")+(f.dist!=="any")+f.accepting+f.online}
